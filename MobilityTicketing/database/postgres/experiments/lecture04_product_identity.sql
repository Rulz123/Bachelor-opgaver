\set ON_ERROR_STOP 1

begin;

\echo 'Lecture 4 baseline'
create temp table products_experiment as
select code, name, price, currency from products;
create temp table tickets_experiment as
select id, product_code, price, currency from tickets;
select code, name, price, currency from products_experiment order by code;
select id, product_code, price, currency from tickets_experiment order by id;

alter table products_experiment
    add column product_id bigint generated by default as identity;
create unique index products_product_id_key_experiment on products_experiment (product_id);
alter table tickets_experiment add column product_id bigint;
create index tickets_product_id_idx_experiment on tickets_experiment (product_id);
alter table tickets_experiment add constraint tickets_product_id_fk_experiment
    foreign key (product_id) references products_experiment(product_id) not valid;

\echo 'Expand state preserves product_code and leaves product_id nullable'
select column_name, is_nullable
from information_schema.columns
where table_name in ('products_experiment', 'tickets_experiment')
  and column_name in ('code', 'product_code', 'product_id')
order by table_name, column_name;

update tickets_experiment t
set product_id = p.product_id
from products_experiment p
where t.product_id is null and t.product_code = p.code;

\echo 'First and second backfill results'
select count(*) as unresolved_after_first_backfill
from tickets_experiment where product_id is null;
update tickets_experiment t
set product_id = p.product_id
from products_experiment p
where t.product_id is null and t.product_code = p.code;
select count(*) as unresolved_after_second_backfill
from tickets_experiment where product_id is null;

select count(*) as ticket_count,
       count(product_id) as resolved_product_count,
       count(*) filter (where price is not null) as priced_ticket_count
from tickets_experiment;

insert into tickets_experiment (id, product_code, price, currency)
values ('UNRESOLVED-TICKET', 'MISSING', 1.00, 'DKK');

do $$
begin
    begin
        alter table tickets_experiment alter column product_id set not null;
        raise exception 'NOT NULL was accepted with an unresolved row';
    exception when not_null_violation then
        raise notice 'expected failure: product_id NOT NULL rejected unresolved data';
    end;
end;
$$;

rollback;